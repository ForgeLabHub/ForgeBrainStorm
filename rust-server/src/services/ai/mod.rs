//! Multi-provider AI backend with fallback and load balancing.
//!
//! Supports: GigaChat, OpenAI, Anthropic, Ollama (local), and custom providers.
//! Features:
//! - Automatic failover between providers
//! - Per-provider rate limiting
//! - Response caching
//! - Dynamic provider selection based on availability and cost

pub mod providers;
pub mod router;
pub mod cache;
pub mod distributed_cache;
pub mod dynamic_difficulty;
pub mod rag;
pub mod mock;

pub use mock::{MockProvider, MockAiRouter};

use async_trait::async_trait;
use serde::{Deserialize, Serialize};
use thiserror::Error;

/// AI provider capabilities.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AiCapability {
    QuestionGeneration,
    HintGeneration,
    ExplanationGeneration,
    AnswerEvaluation,
    DynamicDifficulty,
}

/// AI provider configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProviderConfig {
    pub name: String,
    pub provider_type: ProviderType,
    pub api_key: Option<String>,
    pub api_endpoint: Option<String>,
    pub model: String,
    pub max_concurrent: usize,
    pub timeout_secs: u64,
    pub capabilities: Vec<AiCapability>,
    pub cost_per_1k_tokens: f64,
    pub enabled: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum ProviderType {
    GigaChat,
    OpenAI,
    Anthropic,
    Ollama,
    Custom,
}

/// Question generated by AI.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AiQuestion {
    pub question: String,
    pub options: Vec<String>,
    pub correct_index: usize,
    pub explanation: String,
    pub hint: String,
    pub difficulty: String,
    pub category: Option<String>,
}

/// AI generation request.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GenerationRequest {
    pub topic: String,
    pub count: usize,
    pub difficulty: String,
    pub num_options: usize,
    pub capabilities: Vec<AiCapability>,
    pub exclude_hashes: Vec<String>,
}

/// AI generation response.
#[derive(Debug, Clone)]
pub struct GenerationResponse {
    pub questions: Vec<AiQuestion>,
    pub provider_used: String,
    pub tokens_used: u64,
    pub latency_ms: u64,
}

/// AI provider trait — all providers must implement this.
#[async_trait]
pub trait AiProvider: Send + Sync {
    /// Provider name.
    fn name(&self) -> &str;

    /// Check if provider is available (health check).
    async fn is_available(&self) -> bool;

    /// Get provider capabilities.
    fn capabilities(&self) -> &[AiCapability];

    /// Generate questions.
    async fn generate_questions(
        &self,
        request: &GenerationRequest,
    ) -> Result<GenerationResponse, AiError>;

    /// Generate hint for a question.
    async fn generate_hint(&self, question: &str) -> Result<String, AiError>;

    /// Generate explanation for an answer.
    async fn generate_explanation(
        &self,
        question: &str,
        correct_answer: &str,
    ) -> Result<String, AiError>;
}

/// AI errors.
#[derive(Debug, Error)]
pub enum AiError {
    #[error("Provider unavailable: {0}")]
    Unavailable(String),

    #[error("Rate limit exceeded for provider: {0}")]
    RateLimited(String),

    #[error("Invalid response from provider: {0}")]
    InvalidResponse(String),

    #[error("No providers available")]
    NoProvidersAvailable,

    #[error("Timeout")]
    Timeout,

    #[error("Internal error: {0}")]
    Internal(String),
}
