/// Build `count` fallback questions tagged with the requested topic.
pub fn fallback_questions(topic: &str, count: usize) -> Vec<AiQuestion> {
    let count = count.max(1);
    (0..count)
        .map(|i| {
            let (question, options, correct_index, explanation) = BANK[i % BANK.len()];
            AiQuestion {
                question: question.to_string(),
                options: options.iter().map(|o| o.to_string()).collect(),
                correct_index,
                explanation: explanation.to_string(),
                hint: String::new(),
                difficulty: "medium".to_string(),
                category: Some(topic.to_string()),
            }
        })
        .collect()
}
