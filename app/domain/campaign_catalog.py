def get_level(level_id: int) -> dict:
    """Return a level snapshot so callers cannot mutate the catalog."""
    if level_id not in _LEVEL_BY_ID:
        raise NotFoundError("Уровень не найден")
    return dict(_LEVEL_BY_ID[level_id])
